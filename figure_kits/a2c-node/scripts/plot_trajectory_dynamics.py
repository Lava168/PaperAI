#!/usr/bin/env python3
"""Neural Shape Dynamics figure — Module 3 (Graph Neural ODE) showcase.

Given a trained A2C-NODE checkpoint, this rolls the latent trajectory out to
``--max_months`` and emits two figures:

    a) trajectory_curves.png/pdf  — 21 per-region volume curves over time,
                                    averaged across the validation cohort
                                    (or a single example subject with --ptid)
    b) trajectory_brain.gif        — animated glass-brain showing the
                                    predicted per-region atrophy progressing
                                    over time (one frame per time step)

The brain GIF is generated by reusing the same FastSurfer atlas as
``plot_brain_ate.py``: every voxel inherits the predicted volume change of
its region.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import List

import numpy as np
import torch

PROJ_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(PROJ_ROOT))

from a2c_node.data.legacy_cache_dataset import LegacyCacheRealDataset
from a2c_node.data.npz_dataset import longitudinal_collate
from a2c_node.data.clinical_table import ClinicalTable
from a2c_node.models.a2c_node import A2CNode

REGION_NAMES = (
    "Left-Cerebral-WM", "Left-Cerebral-Cortex", "Left-Lateral-Ventricle",
    "Left-Thalamus", "Left-Caudate", "Left-Putamen", "Left-Pallidum",
    "Brain-Stem", "Left-Hippocampus", "Left-Amygdala", "Left-Accumbens",
    "Right-Cerebral-WM", "Right-Cerebral-Cortex", "Right-Lateral-Ventricle",
    "Right-Thalamus", "Right-Caudate", "Right-Putamen", "Right-Pallidum",
    "Right-Hippocampus", "Right-Amygdala", "Right-Accumbens",
)
REGION_TO_FS = [
    [2], list(range(1000, 1036)), [4],
    [10], [11], [12], [13],
    [16], [17], [18], [26],
    [41], list(range(2000, 2036)), [43],
    [49], [50], [51], [52],
    [53], [54], [58],
]


def parse_args():
    p = argparse.ArgumentParser()
    p.add_argument("--ckpt", required=True, type=Path)
    p.add_argument("--data_root", required=True, type=Path)
    p.add_argument("--clinical_csv", default="")
    p.add_argument("--csf_csv", default="")
    p.add_argument("--out_dir", required=True, type=Path)
    p.add_argument("--gpu", default="0")
    p.add_argument("--max_months", type=int, default=72)
    p.add_argument("--n_steps", type=int, default=24,
                   help="number of time stamps for the rollout (frames)")
    p.add_argument("--max_subjects", type=int, default=80)
    p.add_argument("--seed", type=int, default=0)
    p.add_argument("--make_gif", action="store_true",
                   help="emit trajectory_brain.gif (requires nilearn + imageio)")
    p.add_argument("--aparc",
                   default="/home/lry/aibl/fastsurfer_seg/fs_subjects/AIBL_1000_I1111792/"
                           "mri/aparc.DKTatlas+aseg.deep.mgz")
    return p.parse_args()


@torch.no_grad()
def main() -> None:
    args = parse_args()
    args.out_dir.mkdir(parents=True, exist_ok=True)
    import os
    os.environ["CUDA_VISIBLE_DEVICES"] = str(args.gpu)
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")

    full = LegacyCacheRealDataset(str(args.data_root),
                                   min_visits_per_subject=2, augment=False)
    n = len(full); n_train = int(0.8 * n); n_val = max(1, n - n_train)
    g = torch.Generator().manual_seed(args.seed)
    train_idx, val_idx = torch.utils.data.random_split(full, [n_train, n_val], generator=g)
    train_ptids = [full.subjects[i].ptid for i in train_idx.indices]

    clin = None
    if args.clinical_csv:
        clin = ClinicalTable.from_adnimerge(
            args.clinical_csv, csf_csv=args.csf_csv or None,
            include_csf=bool(args.csf_csv))
        clin.fit_stats(train_ptids)
    full = LegacyCacheRealDataset(str(args.data_root),
                                   min_visits_per_subject=2, augment=False, clinical=clin)
    g = torch.Generator().manual_seed(args.seed)
    _, val_idx = torch.utils.data.random_split(full, [n_train, n_val], generator=g)
    eval_indices = list(val_idx.indices)[: args.max_subjects]
    eval_subset = torch.utils.data.Subset(full, eval_indices)
    loader = torch.utils.data.DataLoader(
        eval_subset, batch_size=4, shuffle=False, num_workers=2,
        collate_fn=longitudinal_collate, pin_memory=True)
    print(f"[traj] using {len(eval_indices)} subjects", flush=True)

    model = A2CNode(ode_solver="rk4", ode_use_adjoint=False, encoder_type="aranet",
                    pretrained_encoder=None,
                    tabular_num_features=clin.num_features if clin else 0,
                    tabular_embed_dim=128, tabular_hidden_dim=128).to(device).eval()
    model.load_state_dict(torch.load(args.ckpt, map_location=device), strict=False)

    t_eval = torch.linspace(0., float(args.max_months), args.n_steps).to(device)
    K = model.num_regions

    # Per-region atrophy averaged across subjects, frame-by-frame.
    sum_atr = np.zeros((args.n_steps, K), dtype=np.float64)
    n_seen = 0

    for batch in loader:
        image = batch["image"].to(device, non_blocking=True)
        mask = batch["mask"].to(device, non_blocking=True)
        time_ = batch["time"].to(device, non_blocking=True)
        valid = batch["valid"].to(device, non_blocking=True)
        graph = model.extract_baseline_graph(image, mask, time_, valid)
        h0 = graph["nodes"]; A = graph["adjacency"]; valid_nodes = graph["valid"]
        traj = model.graph_ode(h0, A, t_eval)                        # (T,B,K,C)
        for ti in range(args.n_steps):
            head = model.head(traj[ti], valid_mask=valid_nodes)
            if "atrophy" in head:
                # head["atrophy"]: (B, K) ratio; positive == growth, neg == atrophy
                sum_atr[ti] += head["atrophy"].cpu().numpy().sum(axis=0)
        n_seen += int(image.shape[0])
        print(f"  rolled out {n_seen} subjects", flush=True)

    avg_atr = sum_atr / max(n_seen, 1)                                # (T, K)
    np.savez(args.out_dir / "trajectory_atrophy.npz",
             times=t_eval.cpu().numpy(),
             atrophy=avg_atr, region_names=np.array(REGION_NAMES))
    print(f"[traj] wrote trajectory_atrophy.npz", flush=True)

    # ---------------- (a) line plot --------------------------------------
    from _plot_style import apply as _style
    _style(extra=("nature",))
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    fig, ax = plt.subplots(figsize=(7.0, 4.0))
    cmap = plt.get_cmap("tab20")
    times = t_eval.cpu().numpy()
    for k in range(K):
        ax.plot(times, avg_atr[:, k], color=cmap(k % 20), lw=1.0,
                label=REGION_NAMES[k])
    ax.set_xlabel("Months from baseline")
    ax.set_ylabel(r"Predicted $\Delta V / V_\text{baseline}$")
    ax.set_title("A2C-NODE rollout: per-region atrophy over time")
    ax.axhline(0, color="black", lw=0.5)
    ax.legend(fontsize=6, ncols=2, loc="lower left",
              frameon=False, columnspacing=0.8)
    fig.tight_layout()
    fig.savefig(args.out_dir / "trajectory_curves.png", dpi=300)
    fig.savefig(args.out_dir / "trajectory_curves.pdf")
    plt.close(fig)
    print(f"[traj] wrote trajectory_curves.png / pdf", flush=True)

    # ---------------- (b) brain GIF --------------------------------------
    if not args.make_gif:
        return
    try:
        import nibabel as nib, imageio.v2 as imageio
        from nilearn import plotting
        aparc = nib.load(str(args.aparc))
        atlas = np.asarray(aparc.dataobj, dtype=np.int32)
        affine = aparc.affine
        abs_max = max(1e-3, float(np.max(np.abs(avg_atr))))
        frames = []
        tmp_nii = args.out_dir / "_traj_frame.nii.gz"
        for ti, t in enumerate(times):
            stat = np.zeros(atlas.shape, dtype=np.float32)
            for k in range(K):
                sel = np.isin(atlas, np.asarray(REGION_TO_FS[k], dtype=np.int32))
                stat[sel] = avg_atr[ti, k]
            nib.save(nib.Nifti1Image(stat, affine), tmp_nii)
            fig = plt.figure(figsize=(6, 2.2))
            disp = plotting.plot_glass_brain(
                str(tmp_nii), figure=fig, display_mode="lyr",
                colorbar=False, plot_abs=False, threshold=0.005,
                symmetric_cbar=True, vmin=-abs_max, vmax=abs_max,
                cmap="RdBu_r", title=f"t = {t:.0f} months")
            frame_p = args.out_dir / f"_frame_{ti:03d}.png"
            fig.savefig(frame_p, dpi=150, bbox_inches="tight")
            plt.close(fig)
            frames.append(imageio.imread(frame_p))
        gif_p = args.out_dir / "trajectory_brain.gif"
        imageio.mimsave(gif_p, frames, duration=0.35)
        for fp in args.out_dir.glob("_frame_*.png"):
            fp.unlink()
        tmp_nii.unlink(missing_ok=True)
        print(f"[traj] wrote {gif_p}  ({len(frames)} frames)", flush=True)
    except Exception as e:
        print(f"[traj] GIF skipped: {e}", flush=True)


if __name__ == "__main__":
    main()
