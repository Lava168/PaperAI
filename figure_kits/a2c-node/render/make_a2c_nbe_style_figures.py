def latent_pca_panel(ax, latent_npz: Path) -> None:
    z = np.load(latent_npz)
    H = z["h"].astype(float)
    lab = z["label"]
    H = H - H.mean(axis=0, keepdims=True)
    # SVD PCA avoids relying on sklearn.
    U, S, _ = np.linalg.svd(H, full_matrices=False)
    emb = U[:, :2] * S[:2]
    for c, name in enumerate(CLASSES):
        m = lab == c
        ax.scatter(emb[m, 0], emb[m, 1], s=19, color=CLASS_COLORS[name], alpha=0.75, edgecolor="white", linewidth=0.35, label=f"{name} n={int(m.sum())}")
    ax.set_xlabel("PC1")
    ax.set_ylabel("PC2")
    ax.set_title("Latent subject embedding", loc="left", color=PALETTE["slate"], pad=3)
    ax.legend(loc="best")
    soft_spines(ax)


def feature_network_panel(ax, latent_npz: Path, ate_rows: List[Dict[str, str]]) -> None:
    z = np.load(latent_npz)
    att = z["attention"]
    lab = z["label"]
    ad_att = att[lab == 2].mean(axis=0) if np.any(lab == 2) else att.mean(axis=0)
    mci_att = att[lab == 1].mean(axis=0) if np.any(lab == 1) else att.mean(axis=0)
    region_names = [
        "L-WM", "L-Ctx", "L-LV", "L-Thal", "L-Caud", "L-Put", "L-Pall",
        "Stem", "L-Hip", "L-Amyg", "L-Acc", "R-WM", "R-Ctx",
        "R-LV", "R-Thal", "R-Caud", "R-Put", "R-Pall", "R-Hip",
        "R-Amyg", "R-Acc",
    ]
    rows = sorted(ate_rows, key=lambda r: int(r["region_idx"]))
    ate = np.array([float(r["ate_AD"]) for r in rows])
    score = np.abs(ate) + 0.02 * ad_att
    idx = np.argsort(score)[::-1][:9]
    clean_axes(ax)
    ax.set_xlim(-1.05, 1.05)
    ax.set_ylim(-0.95, 1.0)
    angles = np.linspace(0, 2 * np.pi, len(idx), endpoint=False)
    pos = {k: (0.72 * np.cos(a), 0.62 * np.sin(a)) for k, a in zip(idx, angles)}
    # Draw strongest attention co-activation edges.
    for ii, i in enumerate(idx):
        for j in idx[ii + 1 :]:
            w = min(ad_att[i], ad_att[j])
            if w > 0.015:
                x0, y0 = pos[i]
                x1, y1 = pos[j]
                ax.plot([x0, x1], [y0, y1], color="#CBD5E1", lw=0.4 + 4.0 * w, alpha=0.65, zorder=1)
    for k in idx:
        x, y = pos[k]
        size = 180 + 2400 * ad_att[k]
        color = PALETTE["red"] if ate[k] >= 0 else PALETTE["blue"]
