def clean_axes(ax) -> None:
    ax.set_xticks([])
    ax.set_yticks([])
    for sp in ax.spines.values():
        sp.set_visible(False)


def soft_spines(ax) -> None:
    for side in ["top", "right"]:
        ax.spines[side].set_visible(False)
    for side in ["bottom", "left"]:
        ax.spines[side].set_color(PALETTE["slate"])
        ax.spines[side].set_linewidth(0.65)


def save(fig, name: str, preserve_page: bool = False) -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    if preserve_page:
        fig.savefig(OUT / f"{name}.png", dpi=360)
        fig.savefig(OUT / f"{name}.pdf")
    else:
        fig.savefig(OUT / f"{name}.png", dpi=360, bbox_inches="tight", pad_inches=0.01)
        fig.savefig(OUT / f"{name}.pdf", bbox_inches="tight", pad_inches=0.01)
    plt.close(fig)
    print(f"wrote {OUT / (name + '.png')}")


def imshow_file(ax, path: Path, title: str | None = None, trim: bool = True) -> None:
    if not path.exists():
        ax.text(0.5, 0.5, f"missing\n{path.name}", ha="center", va="center")
        clean_axes(ax)
        return
    im = Image.open(path).convert("RGB")
    arr = np.asarray(im)
    if trim:
        gray = arr.mean(axis=2)
        mask = gray < 250
        if mask.any():
            ys = np.where(mask.any(axis=1))[0]
            xs = np.where(mask.any(axis=0))[0]
            pad = 8
            y0, y1 = max(0, ys[0] - pad), min(arr.shape[0], ys[-1] + pad)
            x0, x1 = max(0, xs[0] - pad), min(arr.shape[1], xs[-1] + pad)
            arr = arr[y0:y1, x0:x1]
    ax.imshow(arr)
    clean_axes(ax)
    if title:
        ax.set_title(title, loc="left", color=PALETTE["slate"], pad=3)


def imshow_file_zoom(
    ax,
    path: Path,
    title: str | None = None,
    crop: Tuple[float, float, float, float] = (0.0, 0.0, 1.0, 1.0),
    trim: bool = True,
) -> None:
    if not path.exists():
        ax.text(0.5, 0.5, f"missing\n{path.name}", ha="center", va="center")
        clean_axes(ax)
        return
    im = Image.open(path).convert("RGB")
    arr = np.asarray(im)
    if trim:
        gray = arr.mean(axis=2)
        mask = gray < 250
        if mask.any():
            ys = np.where(mask.any(axis=1))[0]
            xs = np.where(mask.any(axis=0))[0]
            pad = 4
            y0, y1 = max(0, ys[0] - pad), min(arr.shape[0], ys[-1] + pad)
            x0, x1 = max(0, xs[0] - pad), min(arr.shape[1], xs[-1] + pad)
            arr = arr[y0:y1, x0:x1]
    x0f, y0f, x1f, y1f = crop
