def fig3_decision_panel(ax, prob: np.ndarray, lab: np.ndarray) -> None:
    y = (lab == 2).astype(int)
    p = prob[:, 2]
    n = len(y)
    pi = y.mean()
    th = np.linspace(0.02, 0.80, 80)
    model, all_, none = [], [], []
    for t in th:
        pp = p >= t
        tp = np.sum(pp & (y == 1))
        fp = np.sum(pp & (y == 0))
        odds = t / (1 - t)
        model.append(tp / n - fp / n * odds)
        all_.append(pi - (1 - pi) * odds)
        none.append(0)
    ax.plot(th, model, color=PALETTE["red"], lw=1.25, label="A2C")
    ax.plot(th, all_, color=PALETTE["muted"], lw=0.8, ls="--", label="all")
    ax.plot(th, none, color=PALETTE["ink"], lw=0.7, ls=":", label="none")
    ax.set_ylim(-0.12, max(0.10, max(model) + 0.03))
    ax.set_xlabel("AD-risk threshold", labelpad=0)
    ax.set_ylabel("Net benefit", labelpad=0)
    ax.set_title("AIBL AD decision curve", loc="left", color=PALETTE["slate"], pad=2)
    ax.legend(loc="upper right", fontsize=5.0)
    soft_spines(ax)


def ribbon(ax, x0: float, x1: float, y0a: float, y0b: float, y1a: float, y1b: float, color: str, alpha: float = 0.28) -> None:
    dx = x1 - x0
    verts = [
        (x0, y0a),
        (x0 + dx * 0.35, y0a),
        (x1 - dx * 0.35, y1a),
        (x1, y1a),
        (x1, y1b),
        (x1 - dx * 0.35, y1b),
        (x0 + dx * 0.35, y0b),
        (x0, y0b),
        (x0, y0a),
    ]
    codes = [
        MplPath.MOVETO,
        MplPath.CURVE4,
        MplPath.CURVE4,
        MplPath.CURVE4,
        MplPath.LINETO,
        MplPath.CURVE4,
        MplPath.CURVE4,
        MplPath.CURVE4,
        MplPath.CLOSEPOLY,
    ]
    ax.add_patch(PathPatch(MplPath(verts, codes), facecolor=color, edgecolor="none", alpha=alpha))


def stacked_segments(values: Sequence[float], center: float = 0.5, height: float = 0.72) -> List[Tuple[float, float]]:
    vals = np.asarray(values, dtype=float)
    vals = vals / max(vals.sum(), 1e-8)
    y = center - height / 2
    out = []
    for v in vals:
        y2 = y + height * float(v)
        out.append((y, y2))
        y = y2
    return out


