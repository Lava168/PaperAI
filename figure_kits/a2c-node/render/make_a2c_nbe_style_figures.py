def box(ax, xy, wh, text, fc, ec=None, fontsize=7.0, lw=0.8, radius=0.02):
    ec = ec or PALETTE["ink"]
    x, y = xy
    w, h = wh
    patch = FancyBboxPatch(
        (x, y),
        w,
        h,
        boxstyle=f"round,pad=0.012,rounding_size={radius}",
        linewidth=lw,
        edgecolor=ec,
        facecolor=fc,
    )
    ax.add_patch(patch)
    ax.text(
        x + w / 2,
        y + h / 2,
        text,
        ha="center",
        va="center",
        fontsize=fontsize,
        color=PALETTE["ink"],
        linespacing=1.15,
    )
    return patch


def arrow(ax, start, end, color=None, lw=0.9, style="-|>", mutation=8, ls="-"):
    arr = FancyArrowPatch(
        start,
        end,
        arrowstyle=style,
        mutation_scale=mutation,
        linewidth=lw,
        linestyle=ls,
        color=color or PALETTE["slate"],
    )
    ax.add_patch(arr)
    return arr


def normalize_image(im: np.ndarray) -> np.ndarray:
    im = np.asarray(im, dtype=float)
    lo, hi = np.percentile(im[im > 0] if np.any(im > 0) else im, [1, 99])
    if hi <= lo:
        hi = lo + 1
    return np.clip((im - lo) / (hi - lo), 0, 1)


def render_mri_atlas(ax, npz_path: Path) -> None:
    d = np.load(npz_path)
    img = normalize_image(d["image"])
    seg = np.asarray(d["seg"])
    axes = [
        ("Axial", 2, int(np.argmax((seg > 0).sum(axis=(0, 1))))),
        ("Coronal", 1, int(np.argmax((seg > 0).sum(axis=(0, 2))))),
        ("Sagittal", 0, int(np.argmax((seg > 0).sum(axis=(1, 2))))),
    ]
    sub = ax.inset_axes([0.02, 0.10, 0.96, 0.78])
    sub.set_xlim(0, 3)
    sub.set_ylim(0, 1)
    clean_axes(sub)
    cmap = ListedColormap(
        [
            "#00000000",
            "#2E6F9E",
            "#4C9A78",
            "#E3A53B",
            "#C9583B",
            "#7556A7",
            "#B65C7A",
            "#8D6E63",
        ]
    )
    for i, (name, axis, idx) in enumerate(axes):
        iax = sub.inset_axes([i / 3 + 0.015, 0.02, 0.30, 0.92])
        if axis == 2:
            im2 = np.rot90(img[:, :, idx])
            sg2 = np.rot90(seg[:, :, idx])
        elif axis == 1:
            im2 = np.rot90(img[:, idx, :])
            sg2 = np.rot90(seg[:, idx, :])
        else:
            im2 = np.rot90(img[idx, :, :])
            sg2 = np.rot90(seg[idx, :, :])
        iax.imshow(im2, cmap="gray", interpolation="nearest")
        masked = np.ma.masked_where(sg2 == 0, sg2 % 7 + 1)
        iax.imshow(masked, cmap=cmap, alpha=0.32, interpolation="nearest")
        iax.set_title(name, fontsize=6.6, color=PALETTE["slate"], pad=1)
        clean_axes(iax)
    ax.set_title("MRI and 21-region atlas mask", loc="left", color=PALETTE["slate"], pad=3)
    clean_axes(ax)


