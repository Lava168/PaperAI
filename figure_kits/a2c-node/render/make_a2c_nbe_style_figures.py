def atlas_centroids(seg: np.ndarray) -> np.ndarray:
    centroids = np.zeros((len(FS_LABELS), 3), dtype=float)
    for i, fs_label in enumerate(FS_LABELS):
        pts = np.argwhere(seg == fs_label)
        if pts.size:
            centroids[i] = pts.mean(axis=0)
        else:
            centroids[i] = np.nan
    return centroids


def view_slice(img: np.ndarray, axis: int, idx: int | None = None) -> np.ndarray:
    if idx is None:
        idx = img.shape[axis] // 2
    if axis == 2:
        return np.rot90(img[:, :, idx])
    if axis == 1:
        return np.rot90(img[:, idx, :])
    return np.rot90(img[idx, :, :])


def project_centroid(c: np.ndarray, axis: int, shape: Tuple[int, int, int]) -> Tuple[float, float]:
    x, y, z = c
    if axis == 2:
        return float(x), float(shape[1] - y)
    if axis == 1:
        return float(x), float(shape[2] - z)
    return float(y), float(shape[2] - z)


def selected_slice_index(seg: np.ndarray, axis: int) -> int:
    if axis == 2:
        return int(np.argmax((seg > 0).sum(axis=(0, 1))))
    if axis == 1:
        return int(np.argmax((seg > 0).sum(axis=(0, 2))))
    return int(np.argmax((seg > 0).sum(axis=(1, 2))))


def draw_single_brain_projection(
    ax,
    npz_path: Path,
    values: np.ndarray,
    title: str,
    fixed_color: str | None = None,
    axis: int = 0,
    max_points: int = 8,
    signed: bool = False,
) -> None:
    d = np.load(npz_path)
    img = normalize_image(d["image"])
    seg = np.asarray(d["seg"])
    idx = selected_slice_index(seg, axis)
    im2 = view_slice(img, axis, idx)
    ax.imshow(im2, cmap="gray", interpolation="nearest", alpha=0.92)
    cent = atlas_centroids(seg)
    vals = np.asarray(values, dtype=float)
    score = np.abs(vals)
    keep = np.argsort(score)[::-1][:max_points]
    mx = max(float(score[keep].max()) if keep.size else 0.0, 1e-8)
    for k in keep:
        if not np.isfinite(cent[k]).all() or score[k] <= 0:
            continue
        px, py = project_centroid(cent[k], axis, img.shape)
        size = 18 + 160 * (score[k] / mx) ** 0.75
        if fixed_color:
            col = fixed_color
        elif signed:
            col = PALETTE["red"] if vals[k] >= 0 else PALETTE["blue"]
        else:
            col = PALETTE["purple"]
        ax.scatter(px, py, s=size, color=col, alpha=0.74, edgecolor="white", linewidth=0.6)
    ax.set_title(title, fontsize=6.4, color=PALETTE["slate"], pad=1)
    clean_axes(ax)


