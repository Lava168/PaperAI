def calibration_deviation_matrix(prob: np.ndarray, lab: np.ndarray, bins: int = 8):
    edges = np.linspace(0, 1, bins + 1)
    dev = np.full((3, bins), np.nan)
    nmat = np.zeros((3, bins), dtype=int)
    ece_num = 0.0
    ece_den = 0
    mce = 0.0
    worst = (0.0, 0, 0, np.zeros(prob.shape[0], dtype=bool))
    for c in range(3):
        y = (lab == c).astype(float)
        for b in range(bins):
            lo, hi = edges[b], edges[b + 1]
            m = (prob[:, c] >= lo) & ((prob[:, c] < hi) if b < bins - 1 else (prob[:, c] <= hi))
            if not np.any(m):
                continue
            gap = float(y[m].mean() - prob[m, c].mean())
            dev[c, b] = gap
            nmat[c, b] = int(m.sum())
            ece_num += int(m.sum()) * abs(gap)
            ece_den += int(m.sum())
            mce = max(mce, abs(gap))
            if int(m.sum()) >= 3 and abs(gap) > worst[0]:
                worst = (abs(gap), c, b, m)
    ece = ece_num / max(ece_den, 1)
    return edges, dev, nmat, ece, mce, worst


