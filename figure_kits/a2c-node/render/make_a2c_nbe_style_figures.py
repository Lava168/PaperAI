    ax.set_xlim(0, 1)
    ax.set_ylim(0, 0.94)
    verts = SIMPLEX_VERTICES
    ax.add_patch(Polygon(verts, closed=True, facecolor="#FFFFFF", edgecolor="#C9D3DF", lw=0.8))
    for t in np.linspace(0.25, 0.75, 3):
        grids = [
            (barycentric_xy(t, 1 - t, 0), barycentric_xy(t, 0, 1 - t)),
            (barycentric_xy(1 - t, t, 0), barycentric_xy(0, t, 1 - t)),
            (barycentric_xy(1 - t, 0, t), barycentric_xy(0, 1 - t, t)),
        ]
        for a, b in grids:
            ax.plot([a[0], b[0]], [a[1], b[1]], color="#EEF2F6", lw=0.45, zorder=0)
    coords = simplex_coords(prob)
    pred = prob.argmax(axis=1)
    for c, name in enumerate(CLASSES):
        m = lab == c
        edge = np.where(pred[m] == c, "#FFFFFF", PALETTE["ink"])
        lw = np.where(pred[m] == c, 0.20, 0.45)
