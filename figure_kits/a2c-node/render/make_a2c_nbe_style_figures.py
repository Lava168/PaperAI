def fig2_dense_decision_panel(ax, prob: np.ndarray, lab: np.ndarray) -> None:
    y = (lab == 2).astype(int)
    p = prob[:, 2]
    n = len(y)
    pi = y.mean()
    th = np.linspace(0.03, 0.80, 70)
    model, all_, none = [], [], []
    for t in th:
        pp = p >= t
        tp = np.sum(pp & (y == 1))
        fp = np.sum(pp & (y == 0))
        odds = t / (1 - t)
        model.append(tp / n - fp / n * odds)
        all_.append(pi - (1 - pi) * odds)
        none.append(0)
    ax.plot(th, model, color=PALETTE["red"], lw=1.35, label="A2C")
    ax.plot(th, all_, color=PALETTE["muted"], lw=0.8, ls="--", label="all")
    ax.plot(th, none, color=PALETTE["ink"], lw=0.7, ls=":", label="none")
    ax.set_ylim(-0.12, max(0.10, max(model) + 0.03))
    ax.set_xlabel("AD-risk threshold", labelpad=0)
    ax.set_ylabel("Net benefit", labelpad=-1)
    ax.set_title("AD decision curve", loc="left", color=PALETTE["slate"], pad=2)
    ax.legend(loc="upper right", fontsize=4.6, handlelength=1.4)
    soft_spines(ax)


def apply_prior(prob: np.ndarray, target_prior: Sequence[float], train_prior: Sequence[float]) -> np.ndarray:
    target = np.asarray(target_prior, dtype=float)
    train = np.asarray(train_prior, dtype=float)
    shifted = prob * (target / np.maximum(train, 1e-8))[None, :]
    return shifted / np.maximum(shifted.sum(axis=1, keepdims=True), 1e-8)


