def calibration_bins(prob: np.ndarray, y: np.ndarray, bins: int = 8):
    edges = np.linspace(0, 1, bins + 1)
    xs, ys, ns = [], [], []
    for i in range(bins):
        lo, hi = edges[i], edges[i + 1]
        mask = (prob >= lo) & ((prob < hi) if i < bins - 1 else (prob <= hi))
        if mask.sum():
            xs.append(float(prob[mask].mean()))
            ys.append(float(y[mask].mean()))
            ns.append(int(mask.sum()))
    return np.asarray(xs), np.asarray(ys), np.asarray(ns)


