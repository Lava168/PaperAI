def roc_curve_simple(y_true: np.ndarray, score: np.ndarray) -> Tuple[np.ndarray, np.ndarray, float]:
    order = np.argsort(-score)
    y = y_true[order].astype(int)
    pos = max(int(y.sum()), 1)
    neg = max(int((1 - y).sum()), 1)
    tp = np.cumsum(y)
    fp = np.cumsum(1 - y)
    tpr = np.r_[0, tp / pos, 1]
    fpr = np.r_[0, fp / neg, 1]
    auc = float(np.trapezoid(tpr, fpr))
    return fpr, tpr, auc


